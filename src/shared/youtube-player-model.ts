export const BRIDGE_SOURCE = "yt-utils:youtube-player-bridge";

type PlayerTextRun = {
  text?: string;
};

export type TranslationLanguage = {
  languageCode?: string;
  languageName?: string;
};

export type CaptionTrack = {
  languageCode?: string;
  kind?: string;
  name?: {
    simpleText?: string;
    runs?: PlayerTextRun[];
  };
  displayName?: string;
  isTranslatable?: boolean;
  isTranslateable?: boolean;
  translationLanguage?: TranslationLanguage | null;
  vssId?: string;
};

export type AudioTrackMetadata = {
  id?: string;
  name?: string;
  isDefault?: boolean;
  isAutoDubbed?: boolean;
};

export type AudioTrack = {
  id?: string;
  wM?: AudioTrackMetadata;
  C_?: AudioTrackMetadata;
  Iw?: AudioTrackMetadata;
  Z1?: AudioTrackMetadata;
  s1?: AudioTrackMetadata;
  hs?: AudioTrackMetadata;
  US?: AudioTrackMetadata;
  yG?: AudioTrackMetadata;
  captionTracks?: CaptionTrack[];
};

const AUDIO_TRACK_METADATA_KEYS = [
  "wM",
  "C_",
  "Iw",
  "Z1",
  "s1",
  "US",
  "yG",
  "hs",
] as const;

export type AvailableAudioTrack = {
  id: string | null;
  name: string | null;
  isDefault: boolean | null;
  isAutoDubbed: boolean | null;
  languageCode: string | null;
};

export type SubtitleSelection =
  | { mode: "off" }
  | { mode: "track"; track: CaptionTrack };

export type PlayerSnapshot = {
  videoId: string | null;
  audioTrack: AudioTrack | null;
  availableAudioTracks: AvailableAudioTrack[];
  audioLanguage: string | null;
  contentLanguage?: string | null;
  captionTracks: CaptionTrack[];
  translationLanguages: TranslationLanguage[];
  currentCaptionTrack: CaptionTrack | null;
  subtitlesOn: boolean;
  qualityLevel?: string | null;
  availableQualityLevels?: string[];
};

export function summarizePlayerSnapshot(
  snapshot: PlayerSnapshot,
): Record<string, unknown> {
  return {
    audioLanguage: snapshot.audioLanguage,
    availableAudioTrackCount: snapshot.availableAudioTracks.length,
    contentLanguage: snapshot.contentLanguage,
    audioTrack: summarizeAudioTrack(snapshot.audioTrack),
    captionTracks: snapshot.captionTracks.map(summarizeCaptionTrack),
    currentCaptionTrack: summarizeCaptionTrack(snapshot.currentCaptionTrack),
    translationLanguageCount: snapshot.translationLanguages.length,
    subtitlesOn: snapshot.subtitlesOn,
  };
}

export function isAutoGeneratedCaptionTrack(track: CaptionTrack): boolean {
  return (
    normalizeText(track.kind) === "asr" ||
    (normalizeText(track.vssId)?.startsWith("a.") ?? false)
  );
}

export function isPlayerSnapshot(value: unknown): value is PlayerSnapshot {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return false;
  }

  const candidate = value as Record<string, unknown>;
  return (
    (candidate.videoId === null || typeof candidate.videoId === "string") &&
    Array.isArray(candidate.availableAudioTracks) &&
    Array.isArray(candidate.captionTracks) &&
    Array.isArray(candidate.translationLanguages) &&
    typeof candidate.subtitlesOn === "boolean"
  );
}

export function summarizeCaptionTrack(
  track: CaptionTrack | null,
): Record<string, unknown> | null {
  if (!track) {
    return null;
  }

  return {
    languageCode: track.languageCode,
    kind: track.kind,
    vssId: track.vssId,
    translationLanguageCode: track.translationLanguage?.languageCode,
  };
}

export function summarizeAvailableAudioTrack(
  track: AudioTrack,
): AvailableAudioTrack {
  const metadata = readAudioTrackMetadata(track);

  return {
    id: readAudioTrackIdentity(track),
    name: metadata?.name ?? null,
    isDefault: metadata?.isDefault ?? null,
    isAutoDubbed: metadata?.isAutoDubbed ?? null,
    languageCode: normalizeLanguageCode(metadata?.id),
  };
}

function summarizeAudioTrack(
  track: AudioTrack | null,
): Record<string, unknown> | null {
  if (!track) {
    return null;
  }

  const { captionTracks: _captionTracks, ...metadata } = track;
  return {
    ...metadata,
    recognizedMetadata: readAudioTrackMetadata(track),
  };
}

export type BridgeRequest = {
  source: typeof BRIDGE_SOURCE;
  kind: "request";
  id: string;
  action:
    | "readSnapshot"
    | "applySelection"
    | "applyAudioTrack"
    | "applyQuality";
  selection?: SubtitleSelection;
  audioTrackId?: string;
  qualityLevel?: string;
};

export type BridgeResponse = {
  source: typeof BRIDGE_SOURCE;
  kind: "response";
  id: string;
  result: PlayerSnapshot | boolean | null;
};

export function isSpanishLanguage(value: string | null | undefined): boolean {
  return normalizeLanguageCode(value)?.startsWith("es") ?? false;
}

export function isEnglishLanguage(value: string | null | undefined): boolean {
  return normalizeLanguageCode(value)?.startsWith("en") ?? false;
}

export function determineSubtitleSelection(
  snapshot: PlayerSnapshot,
): SubtitleSelection {
  if (isSpanishLanguage(snapshot.audioLanguage)) {
    return { mode: "off" };
  }

  const directEnglishTrack = snapshot.captionTracks.find(
    (track) =>
      isEnglishLanguage(track.languageCode) &&
      !isAutoGeneratedCaptionTrack(track),
  );
  if (directEnglishTrack) {
    return { mode: "track", track: directEnglishTrack };
  }

  const autoGeneratedEnglishTrack = snapshot.captionTracks.find(
    (track) =>
      isEnglishLanguage(track.languageCode) &&
      isAutoGeneratedCaptionTrack(track),
  );
  return autoGeneratedEnglishTrack
    ? { mode: "track", track: autoGeneratedEnglishTrack }
    : { mode: "off" };
}

export function readSubtitleSignature(snapshot: PlayerSnapshot): string {
  return [
    snapshot.subtitlesOn ? "on" : "off",
    getCaptionTrackSignature(snapshot.currentCaptionTrack),
  ].join("|");
}

export function matchesSubtitleSelection(
  snapshot: PlayerSnapshot,
  selection: SubtitleSelection,
): boolean {
  if (selection.mode === "off") {
    return snapshot.subtitlesOn === false;
  }

  return (
    snapshot.subtitlesOn === true &&
    getCaptionTrackSignature(snapshot.currentCaptionTrack) ===
      getCaptionTrackSignature(selection.track)
  );
}

function normalizeLanguageCode(
  value: string | null | undefined,
): string | null {
  if (!value) {
    return null;
  }

  const normalized = value
    .trim()
    .toLowerCase()
    .split(".")[0]
    .replaceAll("_", "-");
  return normalized.length > 0 ? normalized : null;
}

function getCaptionTrackSignature(track: CaptionTrack | null): string {
  if (!track) {
    return "caption:none";
  }

  return [
    "caption",
    signaturePart(normalizeLanguageCode(track.languageCode)),
    signaturePart(track.kind),
    signaturePart(track.vssId),
    signaturePart(
      normalizeLanguageCode(track.translationLanguage?.languageCode),
    ),
  ].join(":");
}

// YouTube renames this nested object without notice.
export function readAudioTrackMetadata(
  track: AudioTrack | null,
): AudioTrackMetadata | null {
  if (!track) {
    return null;
  }

  const aliases = AUDIO_TRACK_METADATA_KEYS.map((key) => track[key]);
  const fallback = readGenericAudioTrackMetadata(track);
  const metadata: AudioTrackMetadata = {
    id: readFirstValue([
      ...aliases.map((alias) => alias?.id),
      fallback?.id,
      track.id,
    ]),
    name: readFirstValue([
      ...aliases.map((alias) => alias?.name),
      fallback?.name,
    ]),
    isDefault: readFirstValue([
      ...aliases.map((alias) => alias?.isDefault),
      fallback?.isDefault,
    ]),
    isAutoDubbed: readFirstValue([
      ...aliases.map((alias) => alias?.isAutoDubbed),
      fallback?.isAutoDubbed,
    ]),
  };

  return Object.values(metadata).some((value) => value != null)
    ? metadata
    : null;
}

export function readAudioTrackIdentity(
  track: AudioTrack | null,
): string | null {
  if (!track) {
    return null;
  }

  const id = track.id ?? readAudioTrackMetadata(track)?.id;
  return typeof id === "string" && id.trim().length > 0 ? id : null;
}

type AudioTrackContent = "original" | "dubbed";

export function selectOriginalAudioTrack(
  tracks: AvailableAudioTrack[],
): AvailableAudioTrack | null {
  const byContent = tracks.find(
    (track) => readAudioTrackContent(track.id) === "original",
  );
  if (byContent) {
    return byContent;
  }

  const byName = tracks.find(
    (track) =>
      readAudioTrackContent(track.id) !== "dubbed" &&
      isOriginalAudioTrackName(track.name),
  );
  if (byName) {
    return byName;
  }

  const candidates = tracks.filter(
    (track) => readAudioTrackContent(track.id) !== "dubbed",
  );

  return (
    candidates.find((track) => track.isAutoDubbed === false) ??
    candidates.find((track) => track.isDefault === true) ??
    null
  );
}

function readAudioTrackContent(
  id: string | null | undefined,
): AudioTrackContent | null {
  const encoded = id?.split(";").pop()?.trim();
  if (!encoded) {
    return null;
  }

  try {
    const decoded = globalThis.atob(encoded);
    if (decoded.includes("original")) {
      return "original";
    }
    if (decoded.includes("dubbed")) {
      return "dubbed";
    }
  } catch {
    return null;
  }

  return null;
}

function isOriginalAudioTrackName(name: string | null): boolean {
  return Boolean(name && /original/i.test(name));
}

const GENERIC_AUDIO_METADATA_EXCLUDED_KEYS = new Set([
  "id",
  "captionTracks",
  "captionsInitialState",
  "xtags",
  "Z",
  "A",
  "B",
  "K",
  "S",
  "W",
]);

function readGenericAudioTrackMetadata(
  track: AudioTrack,
): AudioTrackMetadata | null {
  for (const [key, value] of Object.entries(track)) {
    if (
      GENERIC_AUDIO_METADATA_EXCLUDED_KEYS.has(key) ||
      (AUDIO_TRACK_METADATA_KEYS as readonly string[]).includes(key)
    ) {
      continue;
    }

    if (isAudioTrackMetadataShape(value)) {
      return value;
    }
  }

  return null;
}

function isAudioTrackMetadataShape(
  value: unknown,
): value is AudioTrackMetadata {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return false;
  }

  const candidate = value as Record<string, unknown>;
  const id = candidate.id;
  const name = candidate.name;
  return (
    (typeof id === "string" && id.length > 0) ||
    (typeof name === "string" && name.length > 0)
  );
}

function signaturePart(value: string | null | undefined): string {
  return value || "none";
}

function normalizeText(value: string | null | undefined): string | null {
  if (!value) {
    return null;
  }

  const normalized = value.trim().toLowerCase();
  return normalized.length > 0 ? normalized : null;
}

function readFirstValue<T>(values: Array<T | null | undefined>): T | undefined {
  return values.find((value): value is T => value != null);
}
